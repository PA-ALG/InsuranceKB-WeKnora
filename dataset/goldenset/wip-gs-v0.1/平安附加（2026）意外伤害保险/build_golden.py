def load_pages(fn):
    text = open(os.path.join(W, fn), encoding="utf-8").read()
    pages = {}
    cur = None
    for line in text.splitlines():
        m = re.match(r"^===== 第(\d+)页 =====\s*$", line)
        if m:
            cur = int(m.group(1))
            pages[cur] = []
        elif cur is not None:
            pages[cur].append(line)
    return {k: "\n".join(v) for k, v in pages.items()}

