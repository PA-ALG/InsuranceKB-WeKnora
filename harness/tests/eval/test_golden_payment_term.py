"""S4j acceptance: the payment term is back in Golden v2, cited on rate-table headers (Spec §3.5).

Protected file: written by Claude. Regenerated by golden_remap from the Golden before S4i: each
product's payment term is present again, every rate-table quote lies inside that page's header
block and holds no row of numbers, and the field leaves the pending list while the other three
fields that cited rate tables stay pending.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import pytest

from insurance_harness.eval.pdf_text import read_pdf
from insurance_harness.eval.product_sources import source_directory
from insurance_harness.evidence.segments import header_block

REPO = Path(__file__).resolve().parents[3]
GOLDEN = REPO / "dataset" / "golden" / "v2"
PRODUCTS = ("1814", "1816", "1824", "1826", "1828")
NUMBER = re.compile(r"^[+-]?\d+(?:[.,]\d+)*%?$")


def data_row(line: str) -> bool:
    tokens = line.split()
    return len(tokens) >= 2 and all(NUMBER.match(token) for token in tokens)


@pytest.mark.parametrize("product", PRODUCTS)
def test_the_payment_term_is_present_on_rate_table_headers(product: str) -> None:
    golden = json.loads((GOLDEN / f"{product}.json").read_text(encoding="utf-8"))
    field = next(f for f in golden["fields"] if f["field_key"] == "premium_payment_term")
    assert field["state"] == "present" and field["value"]
    rates = [e for e in field["evidence"] if e["document"] == "费率表.pdf"]
    assert rates
    pages = {p.page: p for p in read_pdf(source_directory(REPO, product) / "费率表.pdf")}
    for evidence in rates:
        text = pages[evidence["page"]].text
        found = header_block(text)
        assert found is not None
        assert evidence["quote"] in text[found[0] : found[1]]
        assert not any(data_row(line) for line in evidence["quote"].splitlines())


def test_only_the_payment_term_left_the_pending_list() -> None:
    manifest = json.loads((GOLDEN / "manifest.json").read_text(encoding="utf-8"))
    pending = manifest["pending_semantic_review"]
    for product in PRODUCTS:
        assert "premium_payment_term" not in pending[product], product
        assert {"entry_age_range", "premium_payment_frequency"} <= set(pending[product]), product
    for product in ("1814", "1816", "1824", "1826"):
        assert "coverage_period" in pending[product], product


def test_the_restoration_is_recorded_after_the_s4i_revision() -> None:
    manifest = json.loads((GOLDEN / "manifest.json").read_text(encoding="utf-8"))
    revisions = manifest["revisions"]
    s4i = next(i for i, r in enumerate(revisions) if r["cards_version"] == "draft-2026-10-17a")
    # S12b later judged split pieces under the same cards; only the S4j remap restores headers.
    later = [
        r
        for r in revisions[s4i + 1 :]
        if r["cards_version"] == "draft-2026-10-18a" and r.get("method") == "deterministic-remap"
    ]
    assert len(later) == 1 and later[0]["basis"]
    for product in PRODUCTS:
        assert later[0]["products"][product]["restored"] == ["premium_payment_term"], product
