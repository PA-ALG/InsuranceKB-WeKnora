"""S4c-2b-2 acceptance: the quote digest shared with the platform's evidence verifier.

Protected file: written by Claude. The vectors were generated by ``quote_digest`` and are
checked by internal/enterprise/release/quote_digest_vectors_test.go as well, so a change
on either side of the Evidence.quote_sha256 definition fails a test.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from insurance_harness.contracts.knowledge import quote_digest

VECTORS = (
    Path(__file__).resolve().parents[3]
    / "internal/enterprise/release/testdata/quote_digest_vectors.json"
)

# Whitespace Python's str.split() and Go's unicode.IsSpace could disagree on, plus
# invisible characters that are not whitespace and must survive the digest.
EDGE_CHARACTERS = ("\u00a0", "\u3000", "\u0085", "\u2028", "\x1c", "\x1f", "\u200b", "\u180e")


def _vectors() -> list[dict[str, str]]:
    loaded: list[dict[str, str]] = json.loads(VECTORS.read_text(encoding="utf-8"))
    return loaded


@pytest.mark.parametrize("vector", _vectors(), ids=lambda v: v["name"])
def test_quote_digest_matches_the_shared_vectors(vector: dict[str, str]) -> None:
    assert quote_digest({"quote": vector["quote"]}) == vector["digest"]


def test_the_vectors_cover_the_edge_characters() -> None:
    quotes = "".join(v["quote"] for v in _vectors())
    for char in EDGE_CHARACTERS:
        assert char in quotes
